// そのため L() / K() には、文字列リテラル (書き換わらない文字) だけを渡すこと。配列の中身を変える一時的な文字は渡さない
#define CACHE_N 128
struct CacheEnt { const char* key; const char* val; };

static const char* lookup(const UiTextPair* t, int n, CacheEnt* cache, const char* ja) {
  uintptr_t h = ((uintptr_t)ja >> 2) % CACHE_N;
  if (cache[h].key == ja) return cache[h].val;
  const char* r = ja;
  for (int i = 0; i < n; i++) if (strcmp(t[i].ja, ja) == 0) { r = t[i].en; break; }
  cache[h].key = ja; cache[h].val = r;
  return r;
}

const char* L(const char* ja) {
  static CacheEnt cache[CACHE_N];
  if (!ja || g_lang != UI_LANG_EN) return ja;
  return lookup(TEXT, (int)(sizeof(TEXT) / sizeof(TEXT[0])), cache, ja);
}

const char* K(const char* ja) {
  static CacheEnt cache[CACHE_N];
  if (!ja || !ja[0] || g_lang != UI_LANG_EN) return ja;
  return lookup(KEYS, (int)(sizeof(KEYS) / sizeof(KEYS[0])), cache, ja);
}

int ui_text_count(bool keys) { return keys ? (int)(sizeof(KEYS) / sizeof(KEYS[0])) : (int)(sizeof(TEXT) / sizeof(TEXT[0])); }
const char* ui_text_ja(bool keys, int i) { return keys ? KEYS[i].ja : TEXT[i].ja; }
const char* ui_text_en(bool keys, int i) { return keys ? KEYS[i].en : TEXT[i].en; }
